// ====== TextureLoaderNode ======

TextureLoaderNode::TextureLoaderNode(
    const std::string& instanceName,
    NodeType* nodeType
)
    : TypedNode<TextureLoaderNodeConfig>(instanceName, nodeType)
{
}

TextureLoaderNode::~TextureLoaderNode() = default;

void TextureLoaderNode::TypedSetupImpl(TypedSetupContext& ctx) {
    // Graph-scope initialization only (no input access)
    NODE_LOG_DEBUG("TextureLoaderNode: Setup (graph-scope initialization)");

    // Sprint 6.5: Register compile-time task profile for cost estimation
    std::string profileId = GetInstanceName() + "_compile";
    compileProfile_ = GetOrCreateProfile<SimpleTaskProfile>(profileId, profileId, "pipeline");
    if (compileProfile_) {
        RegisterPhaseProfile(TaskProfilePhase::Compile, compileProfile_);
        NODE_LOG_INFO("[TextureLoaderNode] Registered compile profile: " + profileId);
    }
}

void TextureLoaderNode::TypedCompileImpl(TypedCompileContext& ctx) {
    // Sprint 6.5: Start compile timing (RAII - records on scope exit)
    auto compileSample = compileProfile_ ? compileProfile_->Sample() : ITaskProfile::Sampler(nullptr);

    // Access device input (compile-time dependency)
    VulkanDevice* devicePtr = ctx.In(TextureLoaderNodeConfig::VULKAN_DEVICE_IN);
    if (devicePtr == nullptr) {
        throw std::runtime_error("TextureLoaderNode: Invalid device handle");
    }

    SetDevice(devicePtr);

    // Get parameters
    std::string filePath = GetParameterValue<std::string>(TextureLoaderNodeConfig::FILE_PATH, "");
    if (filePath.empty()) {
        // No asset file provided: instead of failing, fall through to the shared
        // GPU-upload path with an in-memory default checkerboard (generated by
        // TextureCacher when filePath is empty). This keeps texture-consuming
        // pipelines runnable with zero hardcoded asset paths.
        NODE_LOG_INFO("[TextureLoaderNode] filePath empty - generating default checkerboard texture");
    }

    LoadTextureResources(filePath);

    // Set typed outputs
    ctx.Out(TextureLoaderNodeConfig::TEXTURE_IMAGE, textureImage);
    ctx.Out(TextureLoaderNodeConfig::TEXTURE_VIEW, textureView);
    ctx.Out(TextureLoaderNodeConfig::TEXTURE_SAMPLER, textureSampler);
    ctx.Out(TextureLoaderNodeConfig::VULKAN_DEVICE_OUT, device);
    // Combined view+sampler for the reflection-driven gatherer path (AR#31): one connection
    // satisfies a GLSL `sampler2D` (VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER) binding.
    ctx.Out(TextureLoaderNodeConfig::TEXTURE_SAMPLER_PAIR,
            ImageSamplerPair{textureView, textureSampler});
}

