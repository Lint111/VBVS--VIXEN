struct Cursor {
    const uint8_t* p; size_t n; size_t at = 0;
    uint32_t U32() { uint32_t v = p[at] | (p[at+1]<<8) | (p[at+2]<<16) | (p[at+3]<<24); at += 4; return v; }
};

// Manual UTVC v2 unwrap of the checked-in fixture: magic(4) + version(u32) + count(u32) +
// count*(id, offset, length) TOC + concatenated sub-buffers, with no padding.
std::vector<std::vector<std::byte>> UnwrapUtvc(const uint8_t* buf, size_t len) {
    Cursor c{buf, len};
    EXPECT_EQ(buf[0], 'U'); EXPECT_EQ(buf[1], 'T'); EXPECT_EQ(buf[2], 'V'); EXPECT_EQ(buf[3], 'C');
    c.at = 4;
    uint32_t version = c.U32();
    EXPECT_EQ(version, 2u);   // UTVC v2: section-addressed id-per-TOC-entry layout (step-7 A)
    uint32_t count = c.U32();
    std::vector<std::pair<uint32_t,uint32_t>> toc;
    for (uint32_t i = 0; i < count; ++i) {
        (void)c.U32();        // section id -- ordinal order matches id order in this fixture
        uint32_t off = c.U32();
        uint32_t length = c.U32();
        toc.push_back({off, length});
    }
    std::vector<std::vector<std::byte>> out;
    for (auto& [off, length] : toc) {
        std::vector<std::byte> section(length);
        std::memcpy(section.data(), buf + off, length);
        out.push_back(std::move(section));
    }
    return out;
}

