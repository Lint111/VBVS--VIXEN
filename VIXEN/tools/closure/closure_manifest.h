#pragma once
// Affected-test manifest model: which capture families a source path can change.
// A family's closure is what its capture processes actually opened (open_recorder) mapped through the
// build graph to source files, plus every source the capture executable is built from. The manifest is
// a generated build product (closure_manifest merge); select answers "which families does this diff touch".
#include <algorithm>
#include <cstdint>
#include <filesystem>
#include <fstream>
#include <map>
#include <set>
#include <sstream>
#include <string>
#include <vector>

namespace Vixen::Closure {

using Families = std::set<std::string>;

// source path (repository-relative) -> families whose closure contains it
class Manifest {
public:
    void Add(const std::string& source, const std::string& family) { rows_[source].insert(family); }
    void AddAll(const std::string& source, const Families& families) { rows_[source].insert(families.begin(), families.end()); }
    const std::map<std::string, Families>& Rows() const { return rows_; }

    // Families touched by a change set. A path outside every closure touches nothing: it is not an input of
    // any capture process.
    Families Select(const std::vector<std::string>& changed) const {
        Families out;
        for (const auto& path : changed) {
            if (const auto row = rows_.find(path); row != rows_.end())
                out.insert(row->second.begin(), row->second.end());
        }
        return out;
    }

    std::string Serialize() const {
        std::ostringstream text;
        text << "# GENERATED by closure_manifest merge from recorded capture closures; do not edit.\n"
                "# source path (repository-relative)<TAB>comma-separated lookdev-* families whose capture closure contains it\n";
        for (const auto& [source, families] : rows_) {
            text << source << '\t';
            bool first = true;
            for (const auto& family : families) { text << (first ? "" : ",") << family; first = false; }
            text << '\n';
        }
        return text.str();
    }

    static Manifest Parse(std::istream& in) {
        Manifest manifest;
        std::string line;
        while (std::getline(in, line)) {
            if (line.empty() || line[0] == '#') continue;
            const auto tab = line.find('\t');
            if (tab == std::string::npos) continue;
            std::stringstream list(line.substr(tab + 1));
            std::string family;
            while (std::getline(list, family, ',')) if (!family.empty()) manifest.Add(line.substr(0, tab), family);
        }
        return manifest;
    }

private:
    std::map<std::string, Families> rows_;
};

// FNV-1a 64 over file bytes: the content identity of an opened artifact (SPIR-V module, library, asset).
inline std::uint64_t ContentHash(const std::filesystem::path& file) {
    std::ifstream in(file, std::ios::binary);
    std::uint64_t hash = 14695981039346656037ULL;
    char buffer[65536];
    while (in.read(buffer, sizeof buffer) || in.gcount() > 0) {
        for (std::streamsize i = 0; i < in.gcount(); ++i) {
            hash ^= static_cast<unsigned char>(buffer[i]);
            hash *= 1099511628211ULL;
        }
    }
    return hash;
}

}  // namespace Vixen::Closure
