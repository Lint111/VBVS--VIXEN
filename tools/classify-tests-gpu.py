#!/usr/bin/env python3
"""Classify CTest tests as gpu or cpu from what they did when they ran.

Runs ctest with the VK_LAYER_VIXEN_gpu_witness Vulkan layer in record mode. The layer logs the first
instance creation, device creation, device-memory allocation and queue submit of every process; this
tool attributes each process to the ctest test that launched it and writes
VIXEN/tests/gpu-class-manifest.tsv (test, class, target, source fingerprint, evidence). CMake applies
the manifest at ctest load time (VixenTestClassApply.cmake) for every entry whose executable sources
still match the recorded fingerprint; other tests keep the link-closure class CMake derived.

  classify-tests-gpu.py --build-dir build/wsl -L 'RenderGraph|SVO' -j 4      run the pass, write manifest
  classify-tests-gpu.py --build-dir build/wsl --witness-dir D --junit J      analyze an existing run
  add --no-write to print the tables without touching the manifest.
"""
import argparse
import collections
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
import xml.etree.ElementTree as ET

ACTION_ORDER = ["vkCreateInstance", "vkCreateDevice", "vkAllocateMemory", "vkQueueSubmit", "vkQueueSubmit2", "vkQueueSubmit2KHR"]
GPU_LOCK = "vixen_gpu_device"
MANIFEST_HEADER = (
    "# test<TAB>class<TAB>target<TAB>source-fingerprint<TAB>evidence\n"
    "# Generated by tools/classify-tests-gpu.py from a witnessed ctest run. Do not edit by hand:\n"
    "# the next pass rewrites it. An entry is ignored (the test falls back to its link-closure class)\n"
    "# once its target's sources no longer match the fingerprint.\n"
)


def ctest_json(build_dir, selection=None):
    cmd = ["ctest", "--show-only=json-v1"]
    if selection:
        cmd += ["-L", selection]
    out = subprocess.run(cmd, cwd=build_dir, check=True, capture_output=True, text=True).stdout
    tests = {}
    for t in json.loads(out)["tests"]:
        props = {p["name"]: p["value"] for p in t.get("properties", [])}
        tests[t["name"]] = {
            "command": t.get("command", []),
            "labels": props.get("LABELS", []),
            "fixtures_required": props.get("FIXTURES_REQUIRED", []),
            "fixtures_setup": props.get("FIXTURES_SETUP", []),
            "locks": props.get("RESOURCE_LOCK", []),
        }
    return tests


def load_exe_table(build_dir):
    path = os.path.join(build_dir, "vixen-test-classes", "exe-classes.tsv")
    by_file, by_target = {}, {}
    if os.path.exists(path):
        for line in open(path):
            if line.startswith("#") or not line.strip():
                continue
            target, file, cls, fingerprint, evidence = line.rstrip("\n").split("\t", 4)
            row = {"target": target, "class": cls, "fingerprint": fingerprint, "evidence": evidence}
            by_file[os.path.realpath(file)] = row
            by_target[target] = row
    return by_file, by_target


def load_manifest(path):
    entries = {}
    if os.path.exists(path):
        for line in open(path):
            if line.startswith("#") or not line.strip():
                continue
            name, cls, target, fingerprint, evidence = line.rstrip("\n").split("\t", 4)
            entries[name] = {"class": cls, "target": target, "fingerprint": fingerprint, "evidence": evidence}
    return entries


def run_ctest(build_dir, selection, jobs, witness_dir, junit, timeout):
    env = dict(os.environ)
    env["VIXEN_GPU_WITNESS_DIR"] = witness_dir
    cmd = ["ctest", "-j", str(jobs), "--output-junit", junit, "--timeout", str(timeout)]
    if selection:
        cmd += ["-L", selection]
    print("+ " + " ".join(cmd), flush=True)
    started = time.time()
    rc = subprocess.run(cmd, cwd=build_dir, env=env).returncode
    return rc, time.time() - started


def read_junit(path):
    status = {}
    if not os.path.exists(path):
        return status
    for case in ET.parse(path).getroot().iter("testcase"):
        name = case.get("name")
        if case.find("failure") is not None or case.find("error") is not None:
            status[name] = "failed"
        elif case.find("skipped") is not None or case.get("status") == "notrun":
            status[name] = "skipped"
        else:
            status[name] = "passed"
    return status


def read_witness(witness_dir):
    """Return {ancestry cmdline -> [(time, action)]} per recorded process."""
    processes = []
    for entry in sorted(os.listdir(witness_dir)):
        if not entry.endswith(".tsv"):
            continue
        ancestry, events = [], []
        for line in open(os.path.join(witness_dir, entry), errors="replace"):
            parts = line.rstrip("\n").split("\t")
            if parts[0] == "proc" and len(parts) >= 3:
                ancestry.append(parts[2])
            elif parts[0] == "event" and len(parts) >= 4:
                events.append((float(parts[3]), parts[2]))
        processes.append((ancestry, sorted(events)))
    return processes


def attribute(tests, processes):
    """Map each test to its recorded GPU actions by matching process ancestry against test commands."""
    by_command = collections.defaultdict(list)
    for name, t in tests.items():
        by_command["\x1f".join(t["command"])].append(name)
    actions = collections.defaultdict(list)
    for ancestry, events in processes:
        owners = set()
        for cmdline in ancestry:
            owners.update(by_command.get(cmdline, []))
        for owner in owners:
            actions[owner].extend(events)
    result = {}
    for name, events in actions.items():
        events.sort()
        seen = []
        for _, action in events:
            if action not in seen:
                seen.append(action)
        result[name] = seen
    return result


def target_of(test, by_file):
    if not test["command"]:
        return None
    return by_file.get(os.path.realpath(test["command"][0]))


def link_guess(test, exe):
    if exe:
        return exe["class"], exe["evidence"]
    labels = test["labels"]
    if "classified-by-link" in labels:
        return ("gpu" if "gpu" in labels else "cpu"), "link: class label"
    return "cpu", "link: command launches no project executable"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--build-dir", required=True)
    ap.add_argument("-L", "--label", default=None, help="ctest -L selection to run (default: everything)")
    ap.add_argument("-j", "--jobs", type=int, default=4)
    ap.add_argument("--timeout", type=int, default=900)
    ap.add_argument("--manifest", default=None)
    ap.add_argument("--witness-dir", default=None, help="analyze this recorded run instead of running ctest")
    ap.add_argument("--junit", default=None)
    ap.add_argument("--no-write", action="store_true")
    ap.add_argument("--table", default=None, help="write the per-test table (tsv) here")
    ap.add_argument("--quiet-tables", action="store_true", help="print summaries only")
    args = ap.parse_args()

    build_dir = os.path.abspath(args.build_dir)
    here = os.path.dirname(os.path.abspath(__file__))
    manifest_path = args.manifest or os.path.join(here, "..", "VIXEN", "tests", "gpu-class-manifest.tsv")
    manifest_path = os.path.abspath(manifest_path)

    all_tests = ctest_json(build_dir)
    selected = ctest_json(build_dir, args.label) if args.label else all_tests
    by_file, by_target = load_exe_table(build_dir)
    old = load_manifest(manifest_path)

    own_dir = None
    if args.witness_dir:
        witness_dir, junit = args.witness_dir, args.junit
        wall = None
    else:
        own_dir = tempfile.mkdtemp(prefix="vixen-witness.")
        witness_dir = own_dir
        junit = os.path.join(own_dir, "junit.xml")
        rc, wall = run_ctest(build_dir, args.label, args.jobs, witness_dir, junit, args.timeout)
        print(f"ctest exit {rc}, {wall:.1f}s wall (Dozen, non-representative timing)")
    status = read_junit(junit) if junit else {}
    actions = attribute(selected, read_witness(witness_dir))

    # Freshness of the manifest the build was configured with.
    fresh, stale, unknown = [], [], []
    for name, t in selected.items():
        exe = target_of(t, by_file)
        entry = old.get(name)
        if entry is None:
            unknown.append(name)
        elif not exe or entry["target"] != exe["target"] or entry["fingerprint"] != exe["fingerprint"]:
            stale.append(name)
        else:
            fresh.append(name)

    rows = {}
    for name, t in selected.items():
        exe = target_of(t, by_file)
        guess, guess_evidence = link_guess(t, exe)
        previous = old.get(name, {}).get("class") or guess
        state = status.get(name, "unknown")
        seen = actions.get(name, [])
        if seen:
            cls = "gpu"
            evidence = f"first: {seen[0]}; seen: {','.join(seen)}"
        elif state == "passed":
            cls = "cpu"
            evidence = "no GPU action in a passing run"
        else:
            cls = previous
            evidence = f"unmeasured ({state}, no GPU action before it ended): kept {previous}"
        rows[name] = {"class": cls, "evidence": evidence, "guess": guess, "guess_evidence": guess_evidence,
                      "previous": previous, "state": state, "exe": exe, "locks": t["locks"],
                      "manifest_state": "fresh" if name in fresh else "stale" if name in stale else "new"}

    # A test that needs a GPU fixture's setup cannot run in the cpu part: it is gpu too.
    setup_owner = collections.defaultdict(list)
    for name, t in all_tests.items():
        for fx in t["fixtures_setup"]:
            setup_owner[fx].append(name)
    changed = True
    while changed:
        changed = False
        for name, t in selected.items():
            if rows[name]["class"] == "gpu":
                continue
            for fx in t["fixtures_required"]:
                owners = [o for o in setup_owner.get(fx, []) if rows.get(o, {}).get("class") == "gpu"]
                if owners:
                    rows[name]["class"] = "gpu"
                    rows[name]["evidence"] = f"fixture: requires GPU fixture {fx} (setup test {owners[0]})"
                    changed = True
                    break

    counts = collections.Counter(r["class"] for r in rows.values())
    disagree = {n: r for n, r in rows.items() if r["class"] != r["guess"]}
    narrowed = {n: r for n, r in rows.items() if r["previous"] == "gpu" and r["class"] == "cpu"}
    widened = {n: r for n, r in rows.items() if r["previous"] == "cpu" and r["class"] == "gpu"}
    hand_removable = {n: r for n, r in rows.items() if r["class"] == "cpu" and GPU_LOCK in r["locks"]}

    print(f"\n== classification: {len(rows)} tests, measured gpu {counts['gpu']}, cpu {counts['cpu']}")
    print(f"== manifest freshness before this pass: fresh {len(fresh)}, stale {len(stale)}, new {len(unknown)}")
    print(f"== link-closure guess: gpu {sum(r['guess'] == 'gpu' for r in rows.values())}, "
          f"cpu {sum(r['guess'] == 'cpu' for r in rows.values())}")
    print(f"== disagreements (link guess vs measured): {len(disagree)}")
    by_exe = collections.defaultdict(list)
    for n, r in disagree.items():
        by_exe[(r["exe"]["target"] if r["exe"] else "-", r["guess"], r["class"])].append(n)
    print(f"{'executable':58} {'link':5} {'run':5} {'tests':>5}  link evidence")
    for (target, guess, cls), names in sorted(by_exe.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        ev = rows[names[0]]["guess_evidence"]
        print(f"{target:58} {guess:5} {cls:5} {len(names):5}  {ev[:110]}")
    print(f"== narrowing: previously gpu, never dispatched, now cpu: {len(narrowed)}")
    print(f"== widening: previously cpu, dispatched GPU work, now gpu: {len(widened)}")
    print(f"== hand-declared {GPU_LOCK} lock on a measured-cpu test (removable): {len(hand_removable)}")
    if not args.quiet_tables:
        for title, group in (("narrowing candidates", narrowed), ("widened (misclassified cpu)", widened)):
            if group:
                print(f"-- {title}")
                for n in sorted(group)[:40]:
                    print(f"   {n}: {group[n]['evidence']}")
                if len(group) > 40:
                    print(f"   ... {len(group) - 40} more")
    if stale:
        print(f"-- stale entries (fall back to link until this pass is written): {len(stale)}")
        for n in sorted(stale)[:10]:
            print(f"   {n}")

    if args.table:
        with open(args.table, "w") as f:
            f.write("test\tclass\tlink_guess\tmanifest_before\tstate\tevidence\tlink_evidence\n")
            for n in sorted(rows):
                r = rows[n]
                f.write(f"{n}\t{r['class']}\t{r['guess']}\t{r['manifest_state']}\t{r['state']}\t{r['evidence']}\t{r['guess_evidence']}\n")

    if not args.no_write:
        merged = {n: e for n, e in old.items() if n not in rows}
        for n, r in rows.items():
            exe = r["exe"]
            merged[n] = {"class": r["class"], "target": exe["target"] if exe else "-",
                         "fingerprint": exe["fingerprint"] if exe else "-", "evidence": r["evidence"]}
        os.makedirs(os.path.dirname(manifest_path), exist_ok=True)
        with open(manifest_path, "w") as f:
            f.write(MANIFEST_HEADER)
            for n in sorted(merged):
                e = merged[n]
                f.write(f"{n}\t{e['class']}\t{e['target']}\t{e['fingerprint']}\t{e['evidence']}\n")
        print(f"wrote {len(merged)} entries to {manifest_path}")

    if own_dir:
        shutil.rmtree(own_dir, ignore_errors=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
